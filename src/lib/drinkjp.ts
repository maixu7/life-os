// Packaged drinks sold in Japan: convenience stores (7-Eleven, FamilyMart, Lawson), supermarkets, drugstores and vending machines.
// One entry per real product line + flavour, named brand + product + flavour, `ja` as printed on the label.
// Values per 100 ml: label figures where known, otherwise typical for that product type (sugar = 炭水化物/糖質).
// Kept compact: each brand group sets the shared English/Japanese prefix, category, emoji and defaults; rows add the product.

import type { Drink, DrinkCat } from "@/lib/drinks";

const HYDRATION: Record<DrinkCat, number> = {
  water: 1, tea: 1, coffee: 0.9, milk: 0.9, "plant milk": 0.9, soda: 0.9, sports: 1, energy: 0.85, juice: 0.85,
  smoothie: 0.8, "yogurt drink": 0.85, protein: 0.85, soup: 0.9, alcohol: 0.6, other: 0.9,
};

// p = protein g, c = caffeine mg, a = % ABV, w = hydration override (per 100 ml); t / e override the group's category / emoji.
type X = { p?: number; c?: number; a?: number; w?: number; t?: DrinkCat; e?: string };
// Row: English suffix, Japanese suffix (a leading "!" replaces the group prefix instead of extending it), ml, kcal, sugar, extras.
type R = readonly [en: string, ja: string, ml: number, kcal100: number, sugar100: number, x?: X];
type G = readonly [brand: string, brandJa: string, cat: DrinkCat, emoji: string, x: X, rows: readonly R[]];

const join = (a: string, b: string) => (b.startsWith("!") ? b.slice(1) : [a, b].filter(Boolean).join(" "));

const make = ([brand, brandJa, cat0, emoji0, gx, rows]: G): Drink[] =>
  rows.map(([en, ja, ml, kcal100, sugar100, rx]) => {
    const x: X = { ...gx, ...rx };
    const cat = x.t ?? cat0;
    const r: Drink = { name: join(brand, en), cat, emoji: x.e ?? emoji0, ml, kcal100, sugar100 };
    const j = join(brandJa, ja);
    if (j) r.ja = j;
    if (x.p !== undefined) r.protein100 = x.p;
    if (x.c !== undefined) r.caffeine100 = x.c;
    if (x.a !== undefined) r.alcohol = x.a;
    // Same rule as drinks.ts: alcohol dehydrates (beer 5 % ≈ 0.6, wine ≈ 0, spirits 0).
    r.water = x.w ?? (x.a !== undefined ? Math.max(0, Math.round((1 - x.a / 12.5) * 100) / 100) : HYDRATION[cat]);
    return r;
  });


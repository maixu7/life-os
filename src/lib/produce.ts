const norm = (s: string) => s.toLowerCase().trim();

export function produceOf(name: string): Produce | undefined {
  const q = norm(name);
  if (!q) return undefined;
  const exact = PRODUCE.find((p) => norm(p.name) === q || (p.ja && norm(p.ja) === q));
  if (exact) return exact;
  // Strip a parenthetical suffix, e.g. "Spinach (handful)" -> "spinach".
  const base = (s: string) => norm(s.replace(/\s*[(（].*?[)）]\s*/g, " "));
  const byBase = PRODUCE.find((p) => base(p.name) === q || (p.ja && base(p.ja) === q));
  if (byBase) return byBase;
  // Contains match. A name found inside the query wins (longest name first, so
  // "red onion slices" -> "Red onion"); otherwise the query found inside a name
  // (shortest name first, so "pepper" -> the plainest pepper entry).
  let best: Produce | undefined;
  let bestScore = 0;
  for (const p of PRODUCE) {
    for (const key of [p.name, base(p.name), p.ja ?? "", p.ja ? base(p.ja) : ""]) {
      const k = norm(key);
      if (k.length < 2) continue;
      const score = q.includes(k) ? 10000 + k.length : k.includes(q) ? 1000 - k.length : 0;
      if (score > bestScore) {
        best = p;
        bestScore = score;
      }
    }
  }
  return best;
}

export function sized(
  p: Produce,
  size: string,
): { g: number; kcal: number; protein: number; carbs: number; sugar: number; fibre: number; fat: number } {
  const mult = SIZES.find(([s]) => norm(s) === norm(size))?.[1] ?? 1;
  const g = Math.round(p.g * mult);
  const f = g / 100;
  const r1 = (x: number) => Math.round(x * f * 10) / 10;
  return {
    g,
    kcal: Math.round(p.kcal100 * f),
    protein: r1(p.protein100),
    carbs: r1(p.carbs100),
    sugar: r1(p.sugar100),
    fibre: r1(p.fibre100),
    fat: r1(p.fat100),
  };
}
